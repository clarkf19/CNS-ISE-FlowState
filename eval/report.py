"""Render evaluation results as Markdown (docs/results.md)."""

from __future__ import annotations

from datetime import date
from pathlib import Path


def _latency_row(name: str, s: dict) -> str:
    return (f"| {name} | {s['mean_ms']:.3f} | {s['p50_ms']:.3f} | {s['p95_ms']:.3f} "
            f"| {s['p99_ms']:.3f} | {s['n']} |")


def render(r: dict) -> str:
    env = r["environment"]
    lines = [
        "# Evaluation Results",
        "",
        f"Generated by `python -m eval.benchmark` on {date.today().isoformat()} "
        f"(Python {env['python']}, {env['platform']}; {env['requests']} requests, "
        f"{env['clients']} concurrent clients). All traffic is over loopback TCP, so "
        "latencies show the cost of the gateway itself, not network distance.",
        "",
        "## Attack blocking",
        "",
        f"**{r['attack_blocking_rate']:.0%}** of attack scenarios blocked; legitimate traffic "
        f"{'continued normally' if r['legit_traffic_unaffected'] else 'was affected'}.",
        "",
        "| Scenario | Attack | Expected | Observed | Result |",
        "|---|---|---|---|---|",
    ]
    for a in r["attacks"]:
        lines.append(f"| `{a['name']}` | {a['attack']} | {a['expected']} | {a['observed']} | "
                     f"{'Blocked' if a['blocked'] else '**FAILED**'} |")

    rd, af = r["replay_detection"], r["auth_failure_detection"]
    lines += [
        "",
        "## Detection rates",
        "",
        "| Metric | Attempts | Rejected | Rate |",
        "|---|---|---|---|",
        f"| Replay detection | {rd['replayed']} | {rd['rejected']} | {rd['detection_rate']:.0%} |",
        f"| Forged-signature handshakes | {af['forged_handshakes']} | {af['rejected']} "
        f"| {af['detection_rate']:.0%} |",
        "",
        "## Same attacks against the plain forwarding baseline",
        "",
        "| Attack | Succeeds without gateway? |",
        "|---|---|",
    ]
    for name, ok in r["baseline_attack_success"].items():
        lines.append(f"| {name} | {'Yes' if ok else 'No'} |")

    o = r["overhead"]
    lines += [
        "",
        "## Latency (ms)",
        "",
        "| Path | Mean | p50 | p95 | p99 | n |",
        "|---|---|---|---|---|---|",
        _latency_row("Plain baseline (no security)", r["latency_baseline"]),
        _latency_row("Secure gateway", r["latency_gateway"]),
        _latency_row("Handshake (once per session)", r["latency_handshake"]),
        "",
        f"Added latency per request: **{o['added_latency_ms']:.3f} ms** "
        f"({o['relative_latency']:.2f}x the baseline).",
        "",
        "## Throughput",
        "",
        "| Path | Clients | Requests | req/s | Errors |",
        "|---|---|---|---|---|",
    ]
    for name, key in (("Plain baseline", "throughput_baseline"), ("Secure gateway", "throughput_gateway")):
        t = r[key]
        lines.append(f"| {name} | {t['clients']} | {t['requests']} | {t['req_per_s']:.0f} | {t['errors']} |")
    lines += [
        "",
        f"Gateway throughput is {o['throughput_ratio']:.0%} of the baseline.",
        "",
        "## Pipeline cost per stage (mean, microseconds)",
        "",
        "| Stage | Mean (us) |",
        "|---|---|",
    ]
    for stage, us in r["stage_mean_us"].items():
        lines.append(f"| {stage} | {us:.1f} |")
    lines += [
        "",
        "## Encryption overhead (primitive cost, microseconds per operation)",
        "",
        "| Operation | us |",
        "|---|---|",
    ]
    for op, us in r["primitives_us"].items():
        lines.append(f"| {op} | {us:.1f} |")
    return "\n".join(lines) + "\n"


def write_report(results: dict, path: str | Path) -> None:
    Path(path).write_text(render(results), encoding="utf-8")
